test("E2E-04 escalate and confirm write the audit panel", async ({ page }) => {
  await page.goto("/command")
  await openPoint(page, "dp-purana-quila")
  await expect(page.getByRole("button", { name: "ACK" })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "OVERRIDE" })).toHaveCount(0)
  await page.getByLabel("Escalate reason").selectOption({ index: 1 })
  await page.getByTestId("escalate-human-review").click()
  await expect(page).toHaveURL(/\/incident\/dp-purana-quila\/audit/, { timeout: 15000 })
  await expect(page.getByTestId("decision-audit")).toContainText("ESCALATE")
  await expect(page.getByTestId("accountability-clock")).toBeVisible()
  await page.getByRole("tab", { name: "Incident" }).click()
  await page.getByLabel("Confirm agency").selectOption({ index: 1 })
  await page.getByLabel("Confirm reason").fill("Jurisdiction and field evidence reviewed")
  const evidenceBox = page.locator(".evidence-check input[type=checkbox]").first()
  if (await evidenceBox.count()) await evidenceBox.check()
  await page.getByTestId("confirm-decision").click()
  await expect(page).toHaveURL(/\/audit/)
  await expect(page.getByTestId("decision-audit")).toContainText(/OFFICER_CONFIRMED|OPERATIONAL RESPONSIBILITY CONFIRMED|HUMAN DECISION/)
  await expect(page.getByTestId("human-verified")).toContainText("HUMAN DECISION")
  await expect(page.getByTestId("incident-replay")).toBeVisible()
})
