import { expect, test, type Page } from "@playwright/test"

async function openPoint(page: Page, id: string) {
  await page.locator(`tr[data-point-id="${id}"]`).click()
  await expect(page).toHaveURL(new RegExp(`/incident/${id}`))
}

test("E2E-01 cold queue is home at /command", async ({ page }) => {
  await page.goto("/")
  await expect(page).toHaveURL(/\/command/)
  await expect(page.getByRole("region", { name: "Incident queue" })).toBeVisible()
  await expect(page.locator("table tbody tr")).toHaveCount(35)
  await expect(page.getByTestId("command-hero")).toContainText(/District incident command/i)
  await expect(page.getByText("Loading incident queue…")).toHaveCount(0)
  // Columns: Incident | Status | Responsibility | Priority | Next action
  await expect(page.locator("table tbody tr").first().locator("td").nth(1)).toContainText(
    /ACTION REQUIRED|REVIEW REQUIRED|EVIDENCE NEEDED|AWAITING DECISION/,
  )
  await expect(page.getByRole("region", { name: "Incident case" })).toHaveCount(0)
  await expect(page.getByTestId("command-map-hero")).toBeVisible()
  await expect(page.getByTestId("command-queue")).toBeVisible()
  await expect(page.getByTestId("awaiting-next-strip")).toBeVisible()
  await expect(page.getByTestId("aws-honesty")).toHaveCount(0)
  await expect(page.getByText("Volunteer ≠ SCADA")).toHaveCount(0)
  await page.locator("table tbody tr").first().focus()
  await expect(page.locator("table tbody tr").first()).toBeFocused()
})

